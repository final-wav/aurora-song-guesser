// Cache for dynamically resolved iTunes track previews
const dynamicPreviewCache = new Map<string, string>();

/**
 * Searches and fetches real live preview URLs from iTunes API as fallback or enrichment
 */
export async function fetchLiveTrackPreview(song: Song): Promise<string> {
  if (dynamicPreviewCache.has(song.id)) {
    return dynamicPreviewCache.get(song.id)!;
  }

  try {
    const query = encodeURIComponent(`${song.artist} ${song.title}`);
    const res = await fetch(`https://itunes.apple.com/search?term=${query}&entity=song&limit=5`);
    if (res.ok) {
      const data = await res.json();
      if (data.results && data.results.length > 0) {
        // Find best matching track
        const track = data.results.find((t: { previewUrl?: string }) => Boolean(t.previewUrl)) || data.results[0];
        if (track && track.previewUrl) {
          dynamicPreviewCache.set(song.id, track.previewUrl);
          return track.previewUrl;
        }
      }
    }
  } catch (err) {
    console.warn(`Could not fetch dynamic preview for ${song.title}:`, err);
  }

  // Fallback to static catalog preview
  return song.previewUrl;
}
